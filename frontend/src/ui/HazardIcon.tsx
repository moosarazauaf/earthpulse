export function HazardIcon({ hazard, size = 14 }: { hazard: Hazard; size?: number }) {
  const colour = HAZARD_INFO[hazard].colour;
  return (
    <svg className="hazard-icon" width={size} height={size} viewBox="0 0 9 9" shapeRendering="crispEdges" aria-hidden="true">
      {ICONS[hazard].flatMap((row, y) => [...row].map((ch, x) => (ch === "." ? null
        : <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} fill={ch === "+" ? "#fff6dc" : colour} />)))}
    </svg>
  );
}
